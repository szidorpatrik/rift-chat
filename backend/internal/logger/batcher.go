package logger

import (
	"context"
	"log"
	"os"
	"time"

	"github.com/szidorpatrik/rift-chat/backend/rift-chat-api/internal/database"
)

func NewLogBatcher(db *database.Queries, batchSize int, timeout time.Duration) *LogBatcher {
	return &LogBatcher{
		logChannel: make(chan LogEntry, batchSize*2),
		db:         db,
		batchSize:  batchSize,
		timeout:    timeout,
	}
}

// StartWorker should be run as a goroutine when the app starts
func (b *LogBatcher) StartWorker(ctx context.Context) {
	var batch []LogEntry
	ticker := time.NewTicker(b.timeout)
	defer ticker.Stop()

	for {
		select {
		case <-ctx.Done():
			// Server shutting down, flush whatever is left
			if len(batch) > 0 {
				b.flushToDatabase(ctx, batch)
			}
			return

		case entry := <-b.logChannel:
			batch = append(batch, entry)
			if len(batch) >= b.batchSize {
				b.flushToDatabase(ctx, batch)
				batch = nil             // Reset batch
				ticker.Reset(b.timeout) // Reset timer after flush
			}

		case <-ticker.C:
			if len(batch) > 0 {
				b.flushToDatabase(ctx, batch)
				batch = nil // Reset batch
			}
		}
	}
}

func (b *LogBatcher) flushToDatabase(ctx context.Context, batch []LogEntry) {
	times := make([]time.Time, len(batch))
	jsonData := make([]string, len(batch))

	for i, entry := range batch {
		times[i] = entry.CreatedAt
		jsonData[i] = string(entry.Data)
	}

	params := database.BulkInsertJSONLogsParams{
		Times:      times,
		LogRecords: jsonData,
	}

	err := b.db.BulkInsertJSONLogs(ctx, params)
	if err != nil {
		log.Println("ERROR: Failed to bulk insert JSON logs:", err)
	}
}

// BatchWriter connects standard Go logging to our async database batcher
type BatchWriter struct {
	batcher *LogBatcher
}

func NewBatchWriter(batcher *LogBatcher) *BatchWriter {
	return &BatchWriter{
		batcher: batcher,
	}
}

// Write intercepts the bytes generated by slog
func (bw *BatchWriter) Write(p []byte) (n int, err error) {
	// Save a copy from override
	jsonCopy := make([]byte, len(p))
	copy(jsonCopy, p)

	entry := LogEntry{
		CreatedAt: time.Now().UTC(),
		Data:      jsonCopy,
	}

	select {
	case bw.batcher.logChannel <- entry:
		// Success
	default:
		os.Stdout.Write([]byte("WARNING: DB Log Queue Full! Dropping log to stdout: "))
		os.Stdout.Write(p)
	}

	return len(p), nil
}
